-- ============================================================
-- TecSource — estrutura do banco de dados (PostgreSQL / Supabase)
--
-- Idempotente: pode ser executado várias vezes sem apagar dados.
-- Usa CREATE TABLE IF NOT EXISTS, CREATE INDEX IF NOT EXISTS e
-- ALTER TABLE ... ADD COLUMN IF NOT EXISTS.
--
-- Formas de aplicar:
--   1. Supabase → SQL Editor → cole este arquivo e depois sql/view.sql
--   2. cd server && npm run db:setup      (lê DATABASE_URL de .env)
--   3. psql "$DATABASE_URL" -f sql/schema.sql && psql "$DATABASE_URL" -f sql/view.sql
--
-- O banco (database) já existe: no Supabase é o "postgres".
-- Este arquivo NÃO cria banco nem schema — assume o schema "public".
-- ============================================================

-- ------------------------------------------------------------
-- Fuso das janelas de tempo (hoje / 7 / 30 dias)
--
-- Ficam em funções para que "hoje" seja sempre o dia de Brasília,
-- independentemente do fuso da sessão. Isso importa no Supabase:
-- o Connection Pooler (pgbouncer, porta 6543) não mantém SET de
-- sessão entre transações.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION tecsource_hoje()
RETURNS date
LANGUAGE sql
STABLE
SET search_path = pg_catalog, public
AS $$
    SELECT (now() AT TIME ZONE 'America/Sao_Paulo')::date
$$;

-- Início do dia (à meia-noite de Brasília) de "hoje - dias".
-- tecsource_dia(0)  = hoje 00:00 (BRT)
-- tecsource_dia(29) = há 29 dias
-- tecsource_dia(-1) = amanhã 00:00 (usado como limite exclusivo)
CREATE OR REPLACE FUNCTION tecsource_dia(dias integer)
RETURNS timestamptz
LANGUAGE sql
STABLE
SET search_path = pg_catalog, public
AS $$
    SELECT ((now() AT TIME ZONE 'America/Sao_Paulo')::date - dias)::timestamp
           AT TIME ZONE 'America/Sao_Paulo'
$$;

-- ------------------------------------------------------------
-- Tabelas
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tecidos (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           varchar(30)  NOT NULL UNIQUE,
    nome             varchar(120) NOT NULL,
    estoque_minimo_m numeric(10,2) NOT NULL DEFAULT 10.00,
    localizacao      varchar(60),
    criado_em        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tecidos_nome  ON tecidos (nome);
CREATE INDEX IF NOT EXISTS idx_tecidos_local ON tecidos (localizacao);

CREATE TABLE IF NOT EXISTS rolos (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tecido_id        integer NOT NULL REFERENCES tecidos (id),
    codigo_qr        varchar(20) NOT NULL UNIQUE,
    metragem_inicial numeric(10,2) NOT NULL,
    metragem_atual   numeric(10,2) NOT NULL,
    status           varchar(10) NOT NULL DEFAULT 'ativo'
                     CHECK (status IN ('ativo', 'esgotado')),
    criado_em        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_rolos_tecido_stat ON rolos (tecido_id, status);

-- client_key: chave de idempotência enviada pelo cliente (fila offline).
--   O mesmo lançamento reenviado não debita duas vezes.
-- cancelada_em / cancelada_por: estorno. Movimentações canceladas continuam
--   no histórico, mas não entram no saldo nem nos indicadores de consumo.
-- estorno_de_id: aponta para a movimentação que originou o estorno.
CREATE TABLE IF NOT EXISTS movimentacoes (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rolo_id       integer NOT NULL REFERENCES rolos (id),
    tipo          varchar(10) NOT NULL
                  CHECK (tipo IN ('entrada', 'saida', 'ajuste', 'estorno')),
    metros        numeric(10,2) NOT NULL,
    usuario       varchar(100),
    observacao    varchar(255),
    client_key    varchar(64) UNIQUE,
    cancelada_em  timestamptz,
    cancelada_por varchar(100),
    estorno_de_id integer REFERENCES movimentacoes (id),
    criado_em     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_mov_criado        ON movimentacoes (criado_em);
CREATE INDEX IF NOT EXISTS idx_mov_tipo_criado   ON movimentacoes (tipo, criado_em);
CREATE INDEX IF NOT EXISTS idx_mov_estorno       ON movimentacoes (estorno_de_id);

-- ------------------------------------------------------------
-- Bancos criados por versões anteriores do TecSource recebem as
-- colunas novas aqui (no-op quando a tabela acabou de ser criada).
-- ------------------------------------------------------------
ALTER TABLE tecidos       ADD COLUMN IF NOT EXISTS localizacao   varchar(60);
ALTER TABLE movimentacoes ADD COLUMN IF NOT EXISTS client_key    varchar(64);
ALTER TABLE movimentacoes ADD COLUMN IF NOT EXISTS cancelada_em  timestamptz;
ALTER TABLE movimentacoes ADD COLUMN IF NOT EXISTS cancelada_por varchar(100);
ALTER TABLE movimentacoes ADD COLUMN IF NOT EXISTS estorno_de_id integer REFERENCES movimentacoes (id);

-- ------------------------------------------------------------
-- Row Level Security
--
-- O frontend NUNCA fala direto com o Supabase: ele chama a API no
-- Render, que conecta com o usuário dono das tabelas (postgres) e
-- portanto ignora RLS. Já a chave anon/public do Supabase fica sem
-- acesso: sem políticas, o PostgREST não lê nem escreve nada.
-- ------------------------------------------------------------
ALTER TABLE tecidos       ENABLE ROW LEVEL SECURITY;
ALTER TABLE rolos         ENABLE ROW LEVEL SECURITY;
ALTER TABLE movimentacoes ENABLE ROW LEVEL SECURITY;
